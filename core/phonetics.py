def infer_part_of_speech(word: str) -> str:
    """Qo'shimchalarga asoslangan morfologik analizator (Rule-based POS)."""
    w = word.strip().lower()
    if not w:
        return "noun"
    if w.endswith("ly"):
        return "adv"
    if w.endswith(("tion", "sion", "ment", "ness", "ity", "ance", "ence", "er", "or", "ist", "ism", "ship")):
        return "noun"
    if w.endswith(("able", "ible", "ous", "ful", "less", "ive", "ic", "al", "ish")):
        return "adj"
    if w.endswith(("ate", "ize", "ise", "ify", "en")):
        return "verb"
    return "noun"


def infer_phonetic(word: str) -> str:
    """Lug'atda bo'lmagan so'zlar uchun umumiy qoidaviy fonetik taxmin."""
    w = word.strip().lower()
    if not w:
        return ""
    # Sodda transkripsiyalash
    return f"/{w}/"


